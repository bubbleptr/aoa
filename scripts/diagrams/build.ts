// Builds the README diagrams from the design-canvas boards in docs/diagrams/boards.
// For each board: a themed Chinese page, an English copy, and light/dark PNGs of both.
// usage: bun scripts/diagrams/build.ts        (CHROME=<path> to override the browser)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { english } from "./english.ts";

const root = join(import.meta.dir, "../..");
const docs = join(root, "docs");
const boardsDir = join(docs, "diagrams/boards");
const logosDir = join(docs, "diagrams/logos");
const chrome = process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";

// The canvas references uploaded assets by id; these are the same files under readable names.
const logos: Record<string, string> = {
  "22545d1930d276614e1ce91c9ccccdbb": "claude.svg",
  a35c4feb8ec9df790f2450c1f2fe71b7: "pi.svg",
  "28ce80bf1ead921f3181eb86ea2307b9": "openai.svg",
  "30c3b23e5de958e92d14d9ea7ee5ed69": "deepseek.svg",
};

const boards = [
  { name: "architecture", title: "aoa Architecture" },
  { name: "tool-call", title: "aoa Tool Call" },
  { name: "multi-agent", title: "aoa Multi Agent" },
];

const tokens: Record<string, string> = {
  "#f7f8fb": "--bg", "#17202e": "--ink", "#5b6577": "--muted", "rgb(91, 101, 119)": "--muted",
  "#8a95a8": "--line", "#e9effb": "--kernel", "#6f8fd6": "--kernel-edge", "#ffffff": "--tile",
  "#c9d2e3": "--tile-edge", "#a9b2c3": "--dash", "#2f5bd3": "--prim", "#e6edfc": "--icon-bg",
  "#e9ebef": "--icon-neutral", "#e6f4ee": "--builtin", "#3f9a72": "--builtin-edge",
  "#fbf0e1": "--ext", "#c8842d": "--ext-edge", "#efebf9": "--store", "#8a74cf": "--store-edge",
  "#fbeceb": "--block", "#c4504a": "--block-edge",
};

const dark = `--bg: #0e131b; --ink: #e8edf5; --muted: #9aa5b8; --line: #6b7689;
    --kernel: #142037; --kernel-edge: #5576c9; --tile: #101826; --tile-edge: #2c3a52; --dash: #3a4860;
    --prim: #8fb0ff; --icon-bg: #1b2a4a; --icon-neutral: #1c2533;
    --builtin: #0f2a20; --builtin-edge: #4fb488; --ext: #2b1f0e; --ext-edge: #d99a45;
    --store: #1d1834; --store-edge: #9a86e0; --block: #2e1514; --block-edge: #e07a72; color-scheme: dark;`;

function page(boardHtml: string, title: string): { html: string; width: number; height: number } {
  const start = boardHtml.indexOf('<div style="position: relative;');
  const end = boardHtml.lastIndexOf("</x-dc>");
  let body = boardHtml.slice(start, end).trim();

  // Inline the logos so each page is one self-contained file.
  body = body.replace(/<img src="\/_blob\/([0-9a-f]{32})" alt="" style="([^"]*)">/g, (_m, id: string, style: string) => {
    let svg = readFileSync(join(logosDir, logos[id]!), "utf8").trim();
    svg = svg.replace(/ width="\d+" height="\d+"/, "").replace(/fill="#17202e"/g, 'fill="currentColor"');
    return svg.replace("<svg ", `<svg aria-hidden="true" style="${style}; color: var(--ink)" `);
  });

  // Only colors inside style="" can take var(); presentation attributes keep their hex.
  body = body.replace(/style="([^"]*)"/g, (_m, s: string) => {
    for (const [hex, v] of Object.entries(tokens)) s = s.split(hex).join(`var(${v})`);
    return `style="${s}"`;
  });
  body = body.replace(/&quot;/g, "'");

  const [, w, h] = /width: (\d+)px; height: (\d+)px/.exec(body)!;
  const html = `<!doctype html>
<html lang="zh">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@500&family=Space+Grotesk:wght@500;600;700&display=swap">
<style>
/* Generated by scripts/diagrams/build.ts from docs/diagrams/boards; edit the board, not this file. */
:root {
  --bg: #f7f8fb; --ink: #17202e; --muted: #5b6577; --line: #8a95a8;
  --kernel: #e9effb; --kernel-edge: #6f8fd6; --tile: #ffffff; --tile-edge: #c9d2e3; --dash: #a9b2c3;
  --prim: #2f5bd3; --icon-bg: #e6edfc; --icon-neutral: #e9ebef;
  --builtin: #e6f4ee; --builtin-edge: #3f9a72; --ext: #fbf0e1; --ext-edge: #c8842d;
  --store: #efebf9; --store-edge: #8a74cf; --block: #fbeceb; --block-edge: #c4504a;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    ${dark}
  }
}
:root[data-theme="dark"] {
    ${dark}
}
body { margin: 0; padding: 16px; background: var(--bg); color: var(--ink); }
.scroll { overflow-x: auto; }
.scroll > div { margin: 0 auto; }
</style>
</head>
<body>
<div class="scroll">
${body}
</div>
<script>
// "#light" or "#dark" pins the theme, for capturing both images.
const pin = () => { const t = location.hash.slice(1); if (t === "light" || t === "dark") document.documentElement.dataset.theme = t; };
pin(); addEventListener("hashchange", pin);
</script>
</body>
</html>
`;
  return { html, width: Number(w), height: Number(h) };
}

function screenshot(name: string, width: number, height: number) {
  for (const theme of ["light", "dark"]) {
    const r = Bun.spawnSync([
      chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=2",
      `--window-size=${width + 32},${height + 32}`, "--virtual-time-budget=4000",
      `--screenshot=${join(docs, `${name}-${theme}.png`)}`, `file://${join(docs, `${name}.html`)}#${theme}`,
    ], { stderr: "ignore" });
    if (r.exitCode !== 0) throw new Error(`chrome failed on ${name} ${theme}`);
  }
}

for (const { name, title } of boards) {
  const { html, width, height } = page(readFileSync(join(boardsDir, `${name}.dc.html`), "utf8"), title);
  writeFileSync(join(docs, `${name}.html`), html);
  writeFileSync(join(docs, `${name}-en.html`), english(html, name));
  screenshot(name, width, height);
  screenshot(`${name}-en`, width, height);
  console.log(`${name}: ${width}×${height}`);
}
